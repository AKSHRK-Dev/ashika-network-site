/** 緯度による横の縮みを補正するための基準の緯度（大阪のまんなかあたり） */
const BASE_LAT = 34.65;
const COS = Math.cos((BASE_LAT * Math.PI) / 180);
/** 経緯度1度あたりの大きさ。数字が読みやすい桁になるように決めただけ */
const SCALE = 1000;
/** 1平方キロメートルが、この座標系で何平方単位になるか */
const SQ_KM = (SCALE / 111) ** 2;

/** 経緯度を、図の中の座標（右がx＋、下がy＋）に直す */
export function project([lon, lat]: LonLat): [number, number] {
  return [lon * COS * SCALE, -lat * SCALE];
}

type Pt = [number, number];
const round = (v: number) => Math.round(v * 10) / 10;

/** 名前の並びを座標の並びにする */
export function toPoints(ring: readonly Name[]): Pt[] {
  return ring.map((name) => project(P[name]));
}

/**
 * 角をわずかに落とす（Chaikin法）。
 * 点が少ない図なので、かけすぎると輪郭が丸まって地形に見えなくなる。1回だけ。
 */
function chaikin(pts: readonly Pt[], closed: boolean): Pt[] {
  const out: Pt[] = [];
  const n = pts.length;
  if (!closed) out.push(pts[0]!);
  for (let i = 0; i < (closed ? n : n - 1); i++) {
    const [x0, y0] = pts[i]!;
    const [x1, y1] = pts[(i + 1) % n]!;
    out.push([x0 * 0.8 + x1 * 0.2, y0 * 0.8 + y1 * 0.2]);
    out.push([x0 * 0.2 + x1 * 0.8, y0 * 0.2 + y1 * 0.8]);
  }
  if (!closed) out.push(pts[n - 1]!);
  return out;
}

function toD(pts: readonly Pt[], closed: boolean): string {
  let d = '';
  for (let i = 0; i < pts.length; i++) {
    const [x, y] = pts[i]!;
    d += `${i === 0 ? 'M' : 'L'}${round(x)} ${round(y)}`;
  }
  return closed ? `${d}Z` : d;
}

/** 閉じた輪郭のパス */
export function areaPath(...rings: readonly (readonly Name[])[]): string {
  return rings.map((ring) => toD(chaikin(toPoints(ring), true), true)).join('');
}

/** 閉じない線のパス */
export function linePath(ring: readonly Name[]): string {
  return toD(chaikin(toPoints(ring), false), false);
}

/** 座標の並びをそのまま閉じたパスにする（角を落とさない） */
export function rawPath(pts: readonly Pt[]): string {
  return toD(pts, true);
}

/** 点の並びを囲む枠 */
export function bounds(ring: readonly Name[]) {
  const pts = toPoints(ring);
  return {
    minX: Math.min(...pts.map((p) => p[0])),
    minY: Math.min(...pts.map((p) => p[1])),
    maxX: Math.max(...pts.map((p) => p[0])),
    maxY: Math.max(...pts.map((p) => p[1])),
  };
}

/* ---------------------------------------------------------
   市町村の区切り（重み付きボロノイ＝ラゲール図）

   役所の位置だけで区切ると、面積の広い市も狭い町も同じ大きさになってしまう。
   面積を「重み」にして、広い市ほど境界が外へ出るようにしている。
   重みの効き方が直線になるので、境界も直線で引ける。
--------------------------------------------------------- */

/** 凸多角形を、直線 a·x + b·y ≦ c の側だけに切り落とす */
function clipHalfPlane(poly: readonly Pt[], a: number, b: number, c: number): Pt[] {
  const out: Pt[] = [];
  const n = poly.length;
  for (let i = 0; i < n; i++) {
    const p = poly[i]!;
    const q = poly[(i + 1) % n]!;
    const dp = a * p[0] + b * p[1] - c;
    const dq = a * q[0] + b * q[1] - c;
    if (dp <= 0) out.push(p);
    if ((dp < 0 && dq > 0) || (dp > 0 && dq < 0)) {
      const t = dp / (dp - dq);
      out.push([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]);
    }
  }
  return out;
}

/**
 * 面積の効き具合。
 * 大きいほど「広い市ほど大きく」が強く出る。1.0 は面積をそのまま重みにした状態で、
 * それだと狭い町が消えてしまうので、少し弱めてある。
 */
const AREA_WEIGHT = 0.3;

/** 市町村ごとの区切りを計算する。戻り値は座標の並び（空になることはある） */
export function cityCells(box: { minX: number; minY: number; maxX: number; maxY: number }) {
  const m = 400;
  const frame: Pt[] = [
    [box.minX - m, box.minY - m],
    [box.maxX + m, box.minY - m],
    [box.maxX + m, box.maxY + m],
    [box.minX - m, box.maxY + m],
  ];

  const seeds = cities.map((c) => ({ ...c, p: project(c.at), w: c.area * SQ_KM * AREA_WEIGHT }));

  return seeds.map((si) => {
    let poly: Pt[] = frame;
    for (const sj of seeds) {
      if (sj === si) continue;
      const a = 2 * (sj.p[0] - si.p[0]);
      const b = 2 * (sj.p[1] - si.p[1]);
      const c = sj.p[0] ** 2 + sj.p[1] ** 2 - sj.w - (si.p[0] ** 2 + si.p[1] ** 2 - si.w);
      poly = clipHalfPlane(poly, a, b, c);
      if (poly.length === 0) break;
    }
    return { name: si.name, at: si.at, poly };
  });
}
